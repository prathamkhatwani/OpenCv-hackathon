"""Create an original deterministic illustrative road simulation (not training data).
Run from repository root: python roadreport/backend/tools/generate_demo.py
Requires OpenCV/numpy and ffmpeg on PATH. All drawings are generated here.
"""
from pathlib import Path
import json, math, subprocess
import cv2
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'frontend/public/demo';OUT.mkdir(parents=True,exist_ok=True)
W,H,FPS,SECONDS=960,540,24,18
cases=[
 dict(id='contact',title='Pothole in the tyre path',start=0,end=6,contact=True,pothole=True,x=-.75,pulse=5.,decision='Impact-correlated pothole',reason='A visible pothole overlaps the left tyre corridor. The simulated pulse arrives at the expected crossing time.'),
 dict(id='miss',title='Pothole between the tyres',start=6,end=12,contact=False,pothole=True,x=0.,pulse=None,decision='Pothole retained · no contact',reason='The pothole passes through the gap between the two tyres. No pulse is expected; no shock does not mean no pothole.'),
 dict(id='shadow',title='Shadow + unrelated camera shake',start=12,end=18,contact=False,pothole=False,x=1.6,pulse=3.8,decision='Not a pothole · shake rejected',reason='The road mark is a simulated shadow, and the camera shake has an unrelated scripted cause. A jolt alone cannot confirm a pothole.')]
def project(x,z,shake=0):return (round(W/2+650*x/(z+5)),round(90+2400/(z+5)+shake))
def polygon(im,points,color):cv2.fillPoly(im,[np.array(points,dtype=np.int32)],color,cv2.LINE_AA)
pipe=subprocess.Popen(['ffmpeg','-y','-loglevel','error','-f','rawvideo','-vcodec','rawvideo','-pix_fmt','bgr24','-s',f'{W}x{H}','-r',str(FPS),'-i','-','-an','-c:v','libx264','-crf','23','-pix_fmt','yuv420p','-movflags','+faststart',str(OUT/'road-simulation.mp4')],stdin=subprocess.PIPE)
frames=[];motion=[]
rng=np.random.default_rng(42)
texture=rng.integers(-5,6,(H,W,1),dtype=np.int16)
for index in range(FPS*SECONDS):
 t=index/FPS;case=cases[min(int(t//6),2)];local=t-case['start'];pulse=case['pulse']
 amplitude=0 if pulse is None else math.exp(-((local-pulse)/.16)**2)
 shake=amplitude*12*math.sin(65*(local-(pulse or 0)))
 im=np.zeros((H,W,3),np.uint8);im[:]=[161,137,105]
 cv2.rectangle(im,(0,88),(W,H),(69,99,78),-1)
 # Horizon, roadside silhouettes, perspective asphalt.
 for k in range(12):
  x=k*91-30;cv2.rectangle(im,(x,58+(k%3)*8),(x+40,108),(99,113,101),-1)
 polygon(im,[project(-3.8,100,shake),project(3.8,100,shake),project(3.8,0,shake),project(-3.8,0,shake)],(64,68,71))
 mask=np.zeros((H,W),np.uint8)
 polygon(mask,[project(-3.8,100,shake),project(3.8,100,shake),project(3.8,0,shake),project(-3.8,0,shake)],255)
 im=np.where(mask[:,:,None]>0,np.clip(im.astype(np.int16)+texture,0,255),im).astype(np.uint8)
 for x in [-3.5,3.5]:cv2.line(im,project(x,100,shake),project(x,0,shake),(205,211,204),3,cv2.LINE_AA)
 for base in range(0,110,8):
  z=(base-6*local)%104
  polygon(im,[project(-.035,z,shake),project(.035,z,shake),project(.035,z+3.5,shake),project(-.035,z+3.5,shake)],(109,133,145))
 z=30-6*local;box=None
 if z>=-.8:
  cx,cy=project(case['x'],max(z,0),shake);rx=round(650*.28/(max(z,0)+5));ry=max(5,round(rx*.54))
  if case['pothole']:
   cv2.ellipse(im,(cx,cy),(rx+4,ry+3),0,0,360,(114,119,123),-1,cv2.LINE_AA)
   cv2.ellipse(im,(cx,cy),(rx,ry),0,0,360,(27,30,32),-1,cv2.LINE_AA)
   cv2.ellipse(im,(cx,cy+3),(max(1,rx-5),max(1,ry-4)),0,0,180,(48,51,53),2,cv2.LINE_AA)
  else:
   polygon(im,[(cx-rx*2,cy-ry),(cx+rx*3,cy-ry//2),(cx+rx*2,cy+ry),(cx-rx,cy+ry)],(49,57,54))
  if cy-ry<H:box=[max(0,(cx-rx-7)/W),max(0,(cy-ry-7)/H),(rx*2+14)/W,(ry*2+14)/H]
 # Persistent provenance is burned into the video, including when downloaded.
 cv2.rectangle(im,(0,0),(W,46),(25,34,39),-1)
 cv2.putText(im,'ROADREPORT / SYNTHETIC SIMULATION',(24,30),cv2.FONT_HERSHEY_SIMPLEX,.62,(177,220,206),1,cv2.LINE_AA)
 cv2.putText(im,f'CASE {int(t//6)+1}/3',(810,30),cv2.FONT_HERSHEY_SIMPLEX,.55,(220,226,226),1,cv2.LINE_AA)
 cv2.rectangle(im,(0,H-40),(W,H),(25,34,39),-1)
 cv2.putText(im,case['title'],(24,H-15),cv2.FONT_HERSHEY_SIMPLEX,.55,(230,235,235),1,cv2.LINE_AA)
 pipe.stdin.write(im.tobytes())
 corridors=[]
 for center in [-.75,.75]:
  corridors.append([[x/W,y/H] for x,y in [project(center-.11,1,shake),project(center-.11,40,shake),project(center+.11,40,shake),project(center+.11,1,shake)]])
 frames.append(dict(t=round(t,4),box=box,corridors=corridors))
 motion.append(dict(t=round(t,4),motion_score=round(amplitude*8,3),quality=1))
pipe.stdin.close()
if pipe.wait()!=0:raise RuntimeError('ffmpeg encoding failed')
manifest=dict(schema_version=1,source_kind='synthetic',title='Three cases. One important distinction.',fps=FPS,duration_s=SECONDS,width=W,height=H,video='/demo/road-simulation.mp4',cases=cases,frames=frames,motion=motion,provenance='Original procedural illustration generated by tools/generate_demo.py. Scripted ground truth, boxes, corridors and motion. Not detector output, measured IMU or trained-model validation.')
(OUT/'manifest.json').write_text(json.dumps(manifest,separators=(',',':')))
print(f'Created {OUT}: {FPS*SECONDS} frames, {SECONDS}s. Synthetic only.')
